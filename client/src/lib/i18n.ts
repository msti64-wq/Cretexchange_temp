const listeners = new Set<() => void>();

function safeStorage(): LanguageStorage | null {
  if (typeof window === "undefined") return null;
  try {
    return window.localStorage;
  } catch {
    return null;
  }
}

export function isAppLanguage(value: unknown): value is AppLanguage {
  return value === "en" || value === "es";
}

export function readStoredLanguage(storage: LanguageStorage | null = safeStorage()): AppLanguage {
  if (!storage) return "en";

  try {
    const stored = storage.getItem(LANGUAGE_STORAGE_KEY);
    return isAppLanguage(stored) ? stored : "en";
  } catch {
    return "en";
  }
}

export function writeStoredLanguage(language: AppLanguage, storage: LanguageStorage | null = safeStorage()) {
  if (!storage) return;

  try {
    storage.setItem(LANGUAGE_STORAGE_KEY, language);
  } catch {
    // Browser storage can be unavailable in private mode; keep the UI usable.
  }
}

function interpolate(template: string, values?: TranslationValues) {
  if (!values) return template;

  return template.replace(/\{\{(\w+)\}\}/g, (match, key) => {
    const value = values[key];
    return value === undefined || value === null ? match : String(value);
  });
}

export function translate(key: string, language: AppLanguage = "en", values?: TranslationValues) {
  const template = translations[language][key] ?? translations.en[key] ?? key;
  return interpolate(template, values);
}

function getLanguageSnapshot() {
  return readStoredLanguage();
}

function getServerLanguageSnapshot(): AppLanguage {
  return "en";
}

function subscribeLanguage(listener: () => void) {
  listeners.add(listener);

  if (typeof window === "undefined") {
    return () => {
      listeners.delete(listener);
    };
  }

  const handleStorage = (event: StorageEvent) => {
    if (event.key === LANGUAGE_STORAGE_KEY) {
      listener();
    }
  };

  window.addEventListener("storage", handleStorage);

  return () => {
    listeners.delete(listener);
    window.removeEventListener("storage", handleStorage);
  };
}

function notifyLanguageListeners() {
  listeners.forEach((listener) => listener());
}

export function setStoredLanguage(language: AppLanguage, storage: LanguageStorage | null = safeStorage()) {
  writeStoredLanguage(language, storage);
  notifyLanguageListeners();
}

export function useLanguage() {
  const language = useSyncExternalStore(
    subscribeLanguage,
    getLanguageSnapshot,
    getServerLanguageSnapshot,
  );

  const setLanguage = useCallback((nextLanguage: AppLanguage) => {
    setStoredLanguage(nextLanguage);
  }, []);

  const t = useCallback(
    (key: string, values?: TranslationValues) => translate(key, language, values),
    [language],
  );

  return {
    language,
    setLanguage,
    t,
  };
}
